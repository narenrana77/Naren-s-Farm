export function findCropVarietyMeta(cropLabel: string): CropVarietyItem | undefined {
  const normalized = (cropLabel || '').toLowerCase();
  return ALL_CROP_VARIETIES.find(
    (v) =>
      v.label.toLowerCase() === normalized ||
      normalized.includes(v.varietyCode.toLowerCase()) ||
      normalized.includes(v.id.replace('-', ' '))
  );
}
